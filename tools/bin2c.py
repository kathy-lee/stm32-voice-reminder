"""Writes a binary file as a C array: `const uint8_t NAME[]` and `NAME_len`.

Usage: python3 tools/bin2c.py INPUT NAME > OUTPUT.c
"""
import sys


def main() -> None:
    path, name = sys.argv[1], sys.argv[2]
    with open(path, "rb") as f:
        data = f.read()

    print(f"/* Generated by tools/bin2c.py from {path.rsplit('/', 1)[-1]}; do not edit. */")
    print("#include <stddef.h>")
    print("#include <stdint.h>")
    print()
    print(f"const uint8_t {name}[] = {{")
    for i in range(0, len(data), 16):
        print("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
    print("};")
    print(f"const size_t {name}_len = sizeof {name};")


if __name__ == "__main__":
    main()
